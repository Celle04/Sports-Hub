    /**
     * Human readable list of the filters a generated report was built with, so
     * printed and downloaded copies stay understandable later.
     */
    private function filtersLabel(string $report, array $filters): string
    {
        $labels = collect();

        if (! empty($filters['search'])) {
            $labels->push('Search: '.$filters['search']);
        }
        if ($report === 'athletes') {
            $category = $this->athleteCategory($filters);
            if ($category !== 'all') {
                $labels->push('Category: '.self::ATHLETE_CATEGORY_LABELS[$category]);
            }
        }
        if (! empty($filters['sport_id'])) {
            $labels->push('Sport: '.(Sport::find($filters['sport_id'])?->name ?? '—'));
        }
        if (! empty($filters['event_id'])) {
            $labels->push('Event: '.(Event::find($filters['event_id'])?->title ?? '—'));
        }
        if (! empty($filters['status'])) {
            $labels->push('Status: '.$filters['status']);
        }
        if (! empty($filters['grade'])) {
            $labels->push('Year Level: '.$filters['grade']);
        }
        if (! empty($filters['gender'])) {
            $labels->push('Sex: '.$filters['gender']);
        }
        if (! empty($filters['eligibility'])) {
            $labels->push('Eligibility: '.$filters['eligibility']);
        }
        if (! empty($filters['coach_type'])) {
            $labels->push('Coach Type: '.$filters['coach_type']);
        }
        if (! empty($filters['session_id'])) {
            $labels->push('Session: '.(AttendanceSession::find($filters['session_id'])?->displayName() ?? '—'));
        }
        if (! empty($filters['athlete_id'])) {
            $labels->push('Athlete: '.(User::find($filters['athlete_id'])?->name ?? '—'));
        }
        if (! empty($filters['from'])) {
            $labels->push('Date From: '.Carbon::parse($filters['from'])->format('F j, Y'));
        }
        if (! empty($filters['to'])) {
            $labels->push('Date To: '.Carbon::parse($filters['to'])->format('F j, Y'));
        }

        return $labels->isNotEmpty() ? $labels->implode(' · ') : 'All';
    }

    /**
     * Sanitized, meaningful download name: report slug, optional sport or date
     * range, and the generation date. User input is never used verbatim.
     */
    private function filename(string $report, array $filters, string $extension): string
    {
        $parts = [match ($report) {
            'athletes' => 'athlete-list',
            'coaches' => 'coach-list',
            'athlete-summary' => 'athlete-attendance-summary',
            default => 'attendance-report',
        }];

        if ($report === 'athletes') {
            $category = $this->athleteCategory($filters);
            if ($category !== 'all') {
                $parts[] = self::ATHLETE_CATEGORY_LABELS[$category];
            }
        }

        if (! empty($filters['sport_id']) && $sport = Sport::find($filters['sport_id'])) {
            $parts[] = $sport->name;
        }

        if (! empty($filters['event_id']) && $event = Event::find($filters['event_id'])) {
            $parts[] = $event->title;
        }

        if (! empty($filters['from']) && ! empty($filters['to'])) {
            $parts[] = $filters['from'].'-to-'.$filters['to'];
        } elseif (! empty($filters['from'])) {
            $parts[] = 'from-'.$filters['from'];
        } elseif (! empty($filters['to'])) {
            $parts[] = 'to-'.$filters['to'];
        }

        $parts[] = now()->toDateString();

        $slug = collect($parts)
            ->map(fn ($part) => Str::slug((string) $part))
            ->filter()
            ->implode('-');

        return Str::limit($slug, 180, '').'.'.$extension;
    }

    private function overview(): array
    {
        $counts = Attendance::query()
            ->counted()
            ->selectRaw('status, COUNT(*) as total')
            ->groupBy('status')
            ->pluck('total', 'status');

        $countedTotal = (int) $counts->sum();
        $rate = $countedTotal > 0
            ? round((((int) $counts->get('Present', 0)) + ((int) $counts->get('Late', 0))) / $countedTotal * 100, 1)
            : 0.0;

        return [
            ['label' => 'Total Athletes', 'value' => User::where('role', 'Student')->count()],
            ['label' => 'Total Coaches', 'value' => Coach::count()],
            ['label' => 'Total Sports', 'value' => Sport::count()],
            ['label' => 'Total Events', 'value' => Event::count()],
            ['label' => 'Attendance Records', 'value' => Attendance::count()],
            ['label' => 'Attendance Rate', 'value' => $rate.'%'],
        ];
    }

    /**
     * Dropdown data for the active report's filter panel only, so the
     * dashboard itself stays cheap to render.
     */
    private function filterOptions(string $report, array $filters): array
    {
        $options = ['sports' => Sport::orderBy('name')->get()];

        if ($report === 'athletes') {
            $options['grades'] = Application::whereNotNull('grade')->distinct()->orderBy('grade')->pluck('grade');
            $options['genders'] = Application::whereNotNull('gender')->distinct()->orderBy('gender')->pluck('gender');
            $options['statuses'] = ['Active', 'Inactive'];
        }

        if ($report === 'coaches') {
            $options['statuses'] = CoachController::statuses();
            $options['coachTypes'] = CoachController::coachTypes();
        }

        if (in_array($report, ['attendance', 'athlete-summary'], true)) {
            $options['recordStatuses'] = array_merge(config('attendance.record_statuses'), ['Pending']);
            $options['events'] = Event::query()
                ->with('sport')
                ->orderByDesc('starts_at')
                ->limit(200)
                ->get()
                ->map(fn (Event $event) => [
                    'id' => $event->id,
                    'label' => $event->title.' — '.$event->starts_at?->format('M j, Y').' ('.($event->sport?->name ?? 'All sports').')',
                ]);
            $options['sessions'] = AttendanceSession::query()
                ->with('sport')
                ->when(! empty($filters['event_id']), fn ($query, $eventId) => $query->where('event_id', $eventId))
                ->orderByDesc('session_date')
                ->orderByDesc('id')
                ->limit(200)
                ->get()
                ->map(fn (AttendanceSession $session) => [
                    'id' => $session->id,
                    'label' => $session->displayName().' — '.$session->session_date?->format('M j, Y').' ('.$session->effectiveSportName().')',
                ]);
            $options['athletes'] = User::query()
                ->where('role', 'Student')
                ->when(! empty($filters['sport_id']), fn ($query) => $query->where('sport_id', $filters['sport_id']))
                ->orderBy('name')
                ->get(['id', 'name', 'student_id'])
                ->map(fn (User $athlete) => [
                    'id' => $athlete->id,
                    'label' => $athlete->name.($athlete->student_id ? ' ('.$athlete->student_id.')' : ''),
                ]);
        }

        return $options;
    }

