/**
 * Sports Management Reporting Center.
 *
 * Every report is generated straight from the live tables with the same
 * relationships the management modules use, so a report always reflects the
 * database - never a paginated admin page and never hard-coded numbers.
 */
class ReportController extends Controller
{
    public const REPORTS = ['athletes', 'attendance', 'coaches', 'athlete-summary'];

    /**
     * The ways the official athlete list can be categorized. The download
     * always follows the same category as the preview.
     */
    public const ATHLETE_CATEGORIES = ['all', 'sport', 'boys', 'girls'];

    public const ATHLETE_CATEGORY_LABELS = [
        'all' => 'All Athletes',
        'sport' => 'By Sport',
        'boys' => 'Boys',
        'girls' => 'Girls',
    ];

    public const SCHOOL = 'SURIGAO DEL NORTE NATIONAL HIGH SCHOOL';

    public const HUB = 'SPORTSHUB';

    public function index(Request $request): View
    {
        $this->ensureAdministrator();

        $report = $this->reportKey($request);
        $filters = $report ? $this->validateFilters($report, $request) : [];
        $payload = $report ? $this->payload($report, $filters) : null;

        return view('admin.page', array_merge($this->portalData(), [
            'page' => 'reports',
            'heading' => 'Reports',
            'subtitle' => 'Generate and manage official SportsHub reports.',
            'report' => $report,
            'reportPayload' => $payload,
            'filters' => $filters,
            'exportScope' => $report ? $this->exportScope($report, $filters) : 'all',
            'overview' => $this->overview(),
            'filterOptions' => $report ? $this->filterOptions($report, $filters) : [],
            'generatedAt' => now(),
            'generatedBy' => auth()->user()?->name ?? 'Administrator',
        ]));
    }

    /**
     * The scope a download is filed under: the full list or the list grouped
     * sport by sport.
     */
    private function exportScope(?string $report, array $filters): string
    {
        if ($report !== 'athletes') {
            return 'all';
        }

        return ($filters['export_scope'] ?? 'all') === 'sport' ? 'sport' : 'all';
    }

    public function export(Request $request): Response
    {
        $this->ensureAdministrator();

        $validated = $request->validate([
            'format' => ['required', 'in:csv,pdf'],
            'report' => ['nullable', 'in:'.implode(',', self::REPORTS)],
        ]);

        $report = $this->reportKey($request) ?? 'attendance';
        $filters = $this->validateFilters($report, $request);

        /*
         * The administrator picks the scope of the download: the full list, or
         * the list filed sport by sport.
         */
        if ($report === 'athletes' && ($filters['export_scope'] ?? 'all') === 'sport') {
            $filters['category'] = 'sport';
        }

        $payload = $this->payload($report, $filters);
        $filename = $this->filename($report, $filters, $validated['format'] === 'pdf' ? 'pdf' : 'csv');

        if ($validated['format'] === 'pdf') {
            return Pdf::loadView('admin.reports.pdf', [
                'payload' => $payload,
                'generatedAt' => now(),
                'generatedBy' => auth()->user()?->name ?? 'Administrator',
            ])->setPaper('a4', 'landscape')->download($filename);
        }

        return response()->streamDownload(function () use ($payload) {
            $handle = fopen('php://output', 'w');

            fputcsv($handle, [self::SCHOOL]);
            fputcsv($handle, [self::HUB]);
            fputcsv($handle, [$payload['title']]);
            fputcsv($handle, []);
            fputcsv($handle, ['Generated Date', now()->format('F j, Y')]);
            fputcsv($handle, ['Generated By', auth()->user()?->name ?? 'Administrator']);
            fputcsv($handle, ['Filters', $payload['filtersLabel']]);
            fputcsv($handle, []);

            foreach ($payload['summary'] as $item) {
                fputcsv($handle, [$item['label'], $item['value']]);
            }

            fputcsv($handle, []);
            fputcsv($handle, array_column($payload['columns'], 'label'));

            $group = null;

            foreach ($payload['rows'] as $row) {
                /*
                 * A categorized list repeats its heading for every group, so
                 * the downloaded file mirrors the structure of the preview.
                 */
                if ($payload['grouped'] && ($row['group'] ?? null) !== $group) {
                    $group = $row['group'] ?? null;
                    fputcsv($handle, []);
                    fputcsv($handle, [strtoupper((string) $group)]);
                }

                fputcsv($handle, array_map(fn (array $column) => (string) ($row[$column['key']] ?? ''), $payload['columns']));
            }

            fclose($handle);
        }, $filename, ['Content-Type' => 'text/csv; charset=UTF-8']);
    }

    /**
     * Resolves the requested report. The legacy report_type parameter is still
     * accepted so old dashboard links keep working; anything else falls back
     * to the dashboard.
     */
    private function reportKey(Request $request): ?string
    {
        $key = $request->input('report', $request->input('report_type'));

        return is_string($key) && in_array($key, self::REPORTS, true) ? $key : null;
    }

    private function validateFilters(string $report, Request $request): array
    {
        return match ($report) {
            'athletes' => $request->validate([
                'search' => ['nullable', 'string', 'max:100'],
                'sport_id' => ['nullable', 'integer', 'exists:sports,id'],
                'status' => ['nullable', 'in:Active,Inactive'],
                'grade' => ['nullable', 'string', 'max:100'],
                'gender' => ['nullable', 'string', 'max:30'],
                'eligibility' => ['nullable', 'in:Eligible,Not Eligible,Pending'],
                'category' => ['nullable', 'in:'.implode(',', self::ATHLETE_CATEGORIES)],
                'export_scope' => ['nullable', 'in:all,sport'],
            ]),
            'coaches' => $request->validate([
                'search' => ['nullable', 'string', 'max:100'],
                'sport_id' => ['nullable', 'integer', 'exists:sports,id'],
                'status' => ['nullable', 'in:'.implode(',', CoachController::statuses())],
                'coach_type' => ['nullable', 'in:'.implode(',', CoachController::coachTypes())],
            ]),
            'athlete-summary' => $request->validate([
                'sport_id' => ['nullable', 'integer', 'exists:sports,id'],
                'event_id' => ['nullable', 'integer', 'exists:events,id'],
                'session_id' => ['nullable', 'integer', 'exists:attendance_sessions,id'],
                'athlete_id' => ['nullable', 'integer', 'exists:users,id'],
                'from' => ['nullable', 'date'],
                'to' => ['nullable', 'date', 'after_or_equal:from'],
            ]),
            default => $request->validate([
                'sport_id' => ['nullable', 'integer', 'exists:sports,id'],
                'event_id' => ['nullable', 'integer', 'exists:events,id'],
                'session_id' => ['nullable', 'integer', 'exists:attendance_sessions,id'],
                'athlete_id' => ['nullable', 'integer', 'exists:users,id'],
                'from' => ['nullable', 'date'],
                'to' => ['nullable', 'date', 'after_or_equal:from'],
                'status' => ['nullable', 'in:'.implode(',', array_merge(config('attendance.record_statuses'), ['Pending']))],
            ]),
        };
    }

    /**
     * Builds the normalized report payload used by the on-screen preview, the
     * CSV stream and the PDF alike, so every format carries the same rows.
     */
    private function payload(string $report, array $filters): array
    {
        [$title, $rows, $summary, $emptyMessage] = match ($report) {
            'athletes' => $this->athleteReport($filters),
            'coaches' => $this->coachReport($filters),
            'athlete-summary' => $this->athleteAttendanceReport($filters),
            default => $this->attendanceReport($filters),
        };

        $rows = $rows->values();

        return [
            'key' => $report,
            'title' => $title,
            'columns' => $this->columns($report),
            'rows' => $rows,
            'summary' => $summary,
            'filtersLabel' => $this->filtersLabel($report, $filters),
            'emptyMessage' => $emptyMessage,
            // Rows are filed under a heading when the report is categorized,
            // so the download can repeat that heading for every group.
            'grouped' => $report === 'athletes' && $this->athleteCategory($filters) === 'sport',
            // The sports of the list, so a download can be split sport by sport.
            'groups' => $report === 'athletes'
                ? $rows->groupBy('sport_id')->map(fn (Collection $sportRows, $sportId) => [
                    'id' => $sportId,
                    'label' => $sportRows->first()['sport'] ?: 'Unassigned Sport',
                    'value' => $sportRows->count(),
                ])->values()
                : [],
        ];
    }

    /**
     * Complete athlete list: every Student account matching the filters, with
     * the sport and coach relationships Athlete Management displays.
     *
     * The list can be categorized: all athletes, grouped by sport, or split
     * into boys and girls. The download uses the very same rows, so a file
     * always matches the preview.
     */
    private function athleteReport(array $filters): array
    {
        $category = $this->athleteCategory($filters);

        $athletes = User::query()
            ->where('role', 'Student')
            ->with(['sport.coaches', 'applications' => fn ($query) => $query->orderByDesc('created_at')->orderByDesc('id')])
            ->athleteFilters($filters)
            ->orderBy('name')
            ->get()
            ->values();

        if (in_array($category, ['boys', 'girls'], true)) {
            $wanted = $category === 'boys' ? 'Male' : 'Female';
            $athletes = $athletes->filter(fn (User $athlete) => $this->athleteSex($athlete) === $wanted)->values();
        }

        $rows = $athletes
            ->map(function (User $athlete) use ($category) {
                $application = $athlete->applications->first();

                return [
                    'group' => $this->athleteGroup($athlete, $category),
                    'sport_id' => $athlete->sport_id,
                    'student_id' => $athlete->student_id ?: 'Not provided',
                    'name' => $athlete->name,
                    'sport' => $athlete->sport?->name ?? 'Unassigned',
                    'coach' => $athlete->sport?->coaches->pluck('name')->join(', ') ?: 'Unassigned',
                    'email' => $athlete->email ?: 'Not provided',
                    'sex' => $application?->gender ?: 'Not provided',
                    'grade_level' => $athlete->gradeLevel() ?: 'Not provided',
                    'phone' => $athlete->phone ?: 'Not provided',
                    'registered' => $athlete->created_at?->format('M j, Y') ?? '—',
                    'status' => $athlete->status ?? 'Active',
                ];
            })
            ->when($category === 'sport', fn ($rows) => $rows->sortBy('group')->values())
            ->values()
            ->map(fn (array $row, int $index) => ['no' => $index + 1] + $row);

        $summary = [
            ['label' => 'Total Athletes', 'value' => $athletes->count()],
            ['label' => 'Active', 'value' => $athletes->where('status', 'Active')->count()],
            ['label' => 'Inactive', 'value' => $athletes->where('status', 'Inactive')->count()],
            ['label' => 'Sports Represented', 'value' => $athletes->pluck('sport')->filter()->unique()->count()],
        ];

        if (in_array($category, ['boys', 'girls'], true)) {
            $summary[] = ['label' => 'Boys', 'value' => $athletes->filter(fn (User $athlete) => $this->athleteSex($athlete) === 'Male')->count()];
            $summary[] = ['label' => 'Girls', 'value' => $athletes->filter(fn (User $athlete) => $this->athleteSex($athlete) === 'Female')->count()];
        }

        if ($category === 'sport') {
            foreach ($rows->groupBy('group')->sortKeys() as $sport => $sportRows) {
                $summary[] = ['label' => $sport, 'value' => $sportRows->count()];
            }
        }

        return [
            'OFFICIAL ATHLETE LIST',
            $rows,
            $summary,
            'No athletes found.',
        ];
    }

    /**
     * The category the athlete list is built for.
     */
    private function athleteCategory(array $filters): string
    {
        $category = $filters['category'] ?? 'all';

        return in_array($category, self::ATHLETE_CATEGORIES, true) ? $category : 'all';
    }

    /**
     * The label a row is filed under for the chosen category.
     */
    private function athleteGroup(User $athlete, string $category): string
    {
        return match ($category) {
            'sport' => $athlete->sport?->name ?? 'Unassigned Sport',
            'boys' => 'Boys',
            'girls' => 'Girls',
            default => 'All Athletes',
        };
    }

    /**
     * The athlete's recorded sex. It comes from the latest application and
     * falls back to the gender category of the sport they play, so an athlete
     * without an application is still filed in the right group.
     */
    private function athleteSex(User $athlete): string
    {
        $application = $athlete->applications->first();
        $gender = $application?->gender;

        if (in_array($gender, ['Male', 'Female'], true)) {
            return $gender;
        }

        return match ($athlete->sport?->gender) {
            'Boys' => 'Male',
            'Girls' => 'Female',
            default => '',
        };
    }

    /**
     * Complete coach list, with the sport each coach handles.
     */
    private function coachReport(array $filters): array
    {
        $coaches = Coach::query()
            ->with('sport')
            ->coachFilters($filters)
            ->orderBy('name')
            ->get()
            ->values()
            ->map(function (Coach $coach, int $index) {
                return [
                    'no' => $index + 1,
                    'name' => $coach->name,
                    'sport' => $coach->sport?->name ?? 'Unassigned',
                    'coach_type' => $coach->coach_type ?: 'Not assigned',
                    'specialty' => $coach->specialty ?: 'Not provided',
                    'email' => $coach->email ?: 'Not provided',
                    'phone' => $coach->phone ?: 'Not provided',
                    'status' => $coach->status ?? 'Active',
                    'added' => $coach->created_at?->format('M j, Y') ?? '—',
                ];
            });

        return [
            'OFFICIAL COACH LIST',
            $coaches,
            [
                ['label' => 'Total Coaches', 'value' => $coaches->count()],
                ['label' => 'Active', 'value' => $coaches->where('status', 'Active')->count()],
                ['label' => 'Head Coaches', 'value' => $coaches->where('coach_type', 'Head Coach')->count()],
                ['label' => 'Sports Covered', 'value' => $coaches->pluck('sport')->filter()->unique()->count()],
            ],
            'No coaches found.',
        ];
    }

    /**
     * Every attendance record matching the filters. Pending rows are shown but
     * stay out of the rate, following the existing attendance business rules.
     */
    private function attendanceReport(array $filters): array
    {
        $query = $this->attendanceQuery($filters);

        $records = (clone $query)
            ->orderBy('attended_on')
            ->orderBy('id')
            ->get()
            ->values()
            ->map(function (Attendance $record, int $index) {
                return [
                    'no' => $index + 1,
                    'date' => $record->attended_on?->format('M j, Y') ?? '—',
                    'athlete' => $record->athlete?->name ?? '—',
                    'student_id' => $record->athlete?->student_id ?: 'Not provided',
                    'sport' => $record->sportName(),
                    'activity' => $record->displayName(),
                    'time' => $this->sessionTime($record),
                    'status' => $record->status,
                    'check_in' => $record->check_in_time?->format('g:i A') ?? '—',
                ];
            });

        $summary = $this->attendanceSummary($query);

        return [
            'ATTENDANCE REPORT',
            $records,
            $summary['tiles'],
            'No attendance records found for the selected criteria.',
        ];
    }

    /**
     * Attendance performance per athlete. Rates follow the same rule used by
     * the student portal: Present and Late over counted records only, with
     * pending rows and cancelled sessions excluded. Zero records never divide.
     */
    private function athleteAttendanceReport(array $filters): array
    {
        $counted = (clone $this->attendanceQuery($filters))
            ->counted()
            ->selectRaw('user_id, status, COUNT(*) as total')
            ->groupBy('user_id', 'status')
            ->get();

        $byAthlete = $counted->groupBy('user_id');

        $athletes = User::query()
            ->where('role', 'Student')
            ->when(! empty($filters['athlete_id']), fn ($query) => $query->whereKey($filters['athlete_id']))
            ->when(! empty($filters['sport_id']), fn ($query) => $query->where('sport_id', $filters['sport_id']))
            ->with('sport')
            ->orderBy('name')
            ->get()
            ->values();

        $rows = $athletes->map(function (User $athlete, int $index) use ($byAthlete) {
            $statuses = $byAthlete->get($athlete->id, collect());
            $present = (int) $statuses->firstWhere('status', 'Present')?->total ?? 0;
            $late = (int) $statuses->firstWhere('status', 'Late')?->total ?? 0;
            $absent = (int) $statuses->firstWhere('status', 'Absent')?->total ?? 0;
            $excused = (int) $statuses->firstWhere('status', 'Excused')?->total ?? 0;
            $total = $present + $late + $absent + $excused;

            return [
                'no' => $index + 1,
                'name' => $athlete->name,
                'student_id' => $athlete->student_id ?: 'Not provided',
                'sport' => $athlete->sport?->name ?? 'Unassigned',
                'present' => $present,
                'late' => $late,
                'absent' => $absent,
                'excused' => $excused,
                'total' => $total,
                'rate' => $total > 0 ? round((($present + $late) / $total) * 100, 1) : 0.0,
            ];
        });

        $summary = $this->attendanceSummary($this->attendanceQuery($filters));

        return [
            'ATHLETE ATTENDANCE SUMMARY',
            $rows,
            $summary['tiles'],
            'No athletes found.',
        ];
    }

    /**
     * The shared attendance query. Sport, session, athlete, date range and
     * status filters reuse the scopes Attendance Management already relies on.
     */
    private function attendanceQuery(array $filters): Builder
    {
        return Attendance::query()
            ->with(['athlete.sport', 'session.sport', 'event.sport'])
            ->when($filters['sport_id'] ?? null, function ($query, $sportId) {
                $query->where(function ($nested) use ($sportId) {
                    $nested->whereHas('athlete', fn ($athletes) => $athletes->where('sport_id', $sportId))
                        ->orWhereHas('session', fn ($sessionQuery) => $sessionQuery->forSport((int) $sportId));
                });
            })
            ->when($filters['event_id'] ?? null, function ($query, $eventId) {
                $query->where(function ($nested) use ($eventId) {
                    $nested->where('event_id', $eventId)
                        ->orWhereHas('session', fn ($sessionQuery) => $sessionQuery->where('event_id', $eventId));
                });
            })
            ->when($filters['session_id'] ?? null, fn ($query, $sessionId) => $query->forSession((int) $sessionId))
            ->when($filters['athlete_id'] ?? null, fn ($query, $athleteId) => $query->where('user_id', $athleteId))
            ->when($filters['from'] ?? null, fn ($query, $from) => $query->whereDate('attended_on', '>=', $from))
            ->when($filters['to'] ?? null, fn ($query, $to) => $query->whereDate('attended_on', '<=', $to))
            ->when($filters['status'] ?? null, fn ($query, $status) => $query->where('status', $status));
    }

    /**
     * Counted attendance totals for the filtered set. Uses the model's counted
     * scope so Pending rows and cancelled sessions stay out of the rate.
     */
    private function attendanceSummary(Builder $query): array
    {
        $counts = (clone $query)
            ->counted()
            ->selectRaw('status, COUNT(*) as total')
            ->groupBy('status')
            ->pluck('total', 'status');

        $present = (int) $counts->get('Present', 0);
        $late = (int) $counts->get('Late', 0);
        $absent = (int) $counts->get('Absent', 0);
        $excused = (int) $counts->get('Excused', 0);
        $countedTotal = $present + $late + $absent + $excused;
        $pending = (int) (clone $query)->where('status', 'Pending')->count();
        $rate = $countedTotal > 0 ? round((($present + $late) / $countedTotal) * 100, 1) : 0.0;

        return [
            'present' => $present,
            'late' => $late,
            'absent' => $absent,
            'excused' => $excused,
            'pending' => $pending,
            'counted_total' => $countedTotal,
            'rate' => $rate,
            'tiles' => [
                ['label' => 'Total Records', 'value' => $countedTotal + $pending],
                ['label' => 'Present', 'value' => $present],
                ['label' => 'Late', 'value' => $late],
                ['label' => 'Absent', 'value' => $absent],
                ['label' => 'Excused', 'value' => $excused],
                ['label' => 'Pending (not counted)', 'value' => $pending],
                ['label' => 'Attendance Rate', 'value' => $rate.'%'],
            ],
        ];
    }

    private function sessionTime(Attendance $record): string
    {
        if ($record->session?->start_time) {
            return Carbon::parse($record->session->start_time)->format('g:i A');
        }

        if ($record->event?->starts_at) {
            return $record->event->starts_at->format('g:i A');
        }

        return '—';
    }

